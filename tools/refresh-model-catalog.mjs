#!/usr/bin/env node
import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const SOURCE_URL =
  'https://raw.githubusercontent.com/BerriAI/litellm/main/model_prices_and_context_window.json';
const OUTPUT = resolve(
  dirname(fileURLToPath(import.meta.url)),
  '../packages/ai-gateway/src/catalog/model-prices.snapshot.ts'
);

const PROVIDERS = new Set(['anthropic', 'openai', 'gemini', 'openrouter']);
const MODES = new Set(['chat', 'audio_transcription']);

// Curated models the upstream LiteLLM list does not carry yet. Each override
// applies only while its key is absent upstream — once LiteLLM adds it, the
// upstream entry wins. Prices are the provider's current list rates.
const CURATED_OVERRIDES = {
  // Source: https://openrouter.ai/z-ai/glm-5.2 (2026-07-17)
  'openrouter/z-ai/glm-5.2': {
    litellm_provider: 'openrouter',
    mode: 'chat',
    input_cost_per_token: 4.2e-7,
    output_cost_per_token: 0.00000132,
    max_input_tokens: 1000000,
    max_output_tokens: 128000,
  },
};
const FIELDS = [
  'litellm_provider',
  'mode',
  'input_cost_per_token',
  'output_cost_per_token',
  'cache_read_input_token_cost',
  'cache_creation_input_token_cost',
  'input_cost_per_second',
  'max_input_tokens',
  'max_output_tokens',
];

const response = await fetch(SOURCE_URL, {
  signal: AbortSignal.timeout(30_000),
});
if (!response.ok) {
  throw new Error(
    `Failed to fetch ${SOURCE_URL}: ${response.status} ${response.statusText}`
  );
}
const raw = await response.json();

const filtered = {};
for (const key of Object.keys(raw).sort()) {
  const entry = raw[key];
  if (!PROVIDERS.has(entry?.litellm_provider) || !MODES.has(entry?.mode)) {
    continue;
  }
  const projected = {};
  for (const field of FIELDS) {
    if (entry[field] !== undefined) {
      projected[field] = entry[field];
    }
  }
  filtered[key] = projected;
}

for (const [key, entry] of Object.entries(CURATED_OVERRIDES)) {
  if (!(key in filtered)) {
    filtered[key] = entry;
  }
}
const merged = Object.fromEntries(
  Object.keys(filtered)
    .sort()
    .map((key) => [key, filtered[key]])
);

const count = Object.keys(merged).length;
if (count === 0) {
  throw new Error(
    'Filtered catalog is empty — upstream schema may have changed'
  );
}
const banner = `// Generated by tools/refresh-model-catalog.mjs from\n// ${SOURCE_URL}\n// Do not edit by hand — re-run the script to refresh.\n`;
const body = `export const MODEL_PRICES_SNAPSHOT: Record<string, unknown> = ${JSON.stringify(merged, null, 2)};\n`;
writeFileSync(OUTPUT, banner + body);
console.log(`Wrote ${count} models to ${OUTPUT}`);
